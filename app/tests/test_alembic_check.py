"""`alembic check` : modèles ORM ↔ DDL des migrations (CI, §9.6).

Nécessite un PostgreSQL joignable (docker compose) : skip propre sinon.
Dans le conteneur (`docker compose exec app pytest`), la base est up et
les migrations déjà appliquées par le lifespan → le check tourne vraiment.
"""

from __future__ import annotations

import asyncio

import pytest

from transcoder.config import get_settings


def _db_reachable() -> bool:
    import asyncpg

    async def ping() -> bool:
        settings = get_settings()
        try:
            conn = await asyncio.wait_for(
                asyncpg.connect(
                    host=settings.postgres_host,
                    port=settings.postgres_port,
                    user=settings.postgres_user,
                    password=settings.postgres_password,
                    database=settings.postgres_db,
                ),
                timeout=3.0,
            )
        except Exception:
            return False
        await conn.close()
        return True

    return asyncio.run(ping())


@pytest.mark.skipif(not _db_reachable(), reason="PostgreSQL injoignable : check skippé")
def test_models_match_migrations() -> None:
    """Aucune dérive entre les modèles et le schéma migré."""
    from pathlib import Path

    from alembic import command
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected

    app_root = Path(__file__).resolve().parents[1]
    cfg = Config(str(app_root / "alembic.ini"))
    cfg.set_main_option("script_location", str(app_root / "alembic"))
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"modèles et migrations désynchronisés : {exc}")
